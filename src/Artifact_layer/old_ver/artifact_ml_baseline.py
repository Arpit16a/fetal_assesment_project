def prepare_dataset(
    dataset_name: str,
    raw_df: pd.DataFrame,
) -> Dict:
    """
    Prepare one dataset for supervised artifact classification.

    Returns a dictionary containing:

        full dataframe
        labeled dataframe
        feature dataframe
        target
        groups
        metadata
    """

    print_subheader(
        f"{dataset_name} DATASET PREPARATION"
    )

    df = raw_df.copy()

    print(
        f"Raw candidate events: {len(df):,}"
    )

    # --------------------------------------------------------
    # Label column
    # --------------------------------------------------------

    label_column = detect_label_column(df)

    if label_column is None:

        print(
            "❌ No manual label column detected."
        )

        return {
            "status": "NO_LABEL_COLUMN",
            "dataset": dataset_name,
            "raw": df,
        }

    print(
        f"Label column: {label_column}"
    )

    # --------------------------------------------------------
    # Normalize labels
    # --------------------------------------------------------

    df["_normalized_label"] = (
        df[label_column]
        .apply(normalize_label)
    )

    print("\nRaw label distribution:")

    print(
        df[label_column]
        .value_counts(dropna=False)
    )

    print("\nNormalized label distribution:")

    print(
        df["_normalized_label"]
        .value_counts(dropna=False)
    )

    # --------------------------------------------------------
    # Subject
    # --------------------------------------------------------

    subject_column = detect_subject_column(df)

    if subject_column is None:

        print(
            "❌ Subject identifier column not found."
        )

        return {
            "status": "NO_SUBJECT_COLUMN",
            "dataset": dataset_name,
            "raw": df,
        }

    print(
        f"Subject column: {subject_column}"
    )

    # --------------------------------------------------------
    # Keep only supervised labels
    # --------------------------------------------------------

    usable_mask = df["_normalized_label"].isin(
        [
            ARTIFACT_LABEL,
            FETAL_LABEL,
        ]
    )

    supervised = (
        df.loc[usable_mask]
        .copy()
        .reset_index(drop=True)
    )

    uncertain_count = (
        df["_normalized_label"]
        .eq(UNCERTAIN_LABEL)
        .sum()
    )

    unlabeled_count = (
        df["_normalized_label"]
        .isna()
        .sum()
    )

    print(
        f"\nUncertain events excluded: "
        f"{uncertain_count:,}"
    )

    print(
        f"Unlabeled/unknown events excluded: "
        f"{unlabeled_count:,}"
    )

    print(
        f"Supervised events: "
        f"{len(supervised):,}"
    )

    if supervised.empty:

        return {
            "status": "NO_SUPERVISED_EVENTS",
            "dataset": dataset_name,
            "raw": df,
            "supervised": supervised,
        }

    # --------------------------------------------------------
    # Target
    # --------------------------------------------------------

    y = (
        supervised["_normalized_label"]
        .map({
            ARTIFACT_LABEL: 1,
            FETAL_LABEL: 0,
        })
        .astype(int)
    )

    # --------------------------------------------------------
    # Subject groups
    # --------------------------------------------------------

    groups = (
        supervised[subject_column]
        .astype(str)
    )

    # --------------------------------------------------------
    # Feature candidates
    # --------------------------------------------------------

    excluded_columns = set(
        NON_FEATURE_COLUMNS
    )

    excluded_columns.update(
        {
            label_column,
            "_normalized_label",
            subject_column,
        }
    )

    numeric_columns = (
        supervised
        .select_dtypes(
            include=[np.number]
        )
        .columns
        .tolist()
    )

    feature_columns = [
        column
        for column in numeric_columns
        if column not in excluded_columns
    ]

    # Remove columns with no variability
    valid_feature_columns = []

    for column in feature_columns:

        unique_count = (
            supervised[column]
            .nunique(dropna=True)
        )

        if unique_count <= 1:
            continue

        valid_feature_columns.append(column)

    feature_columns = valid_feature_columns

    print(
        f"\nNumeric feature candidates: "
        f"{len(numeric_columns)}"
    )

    print(
        f"Usable feature columns: "
        f"{len(feature_columns)}"
    )

    if feature_columns:

        print("\nFeatures:")

        for column in feature_columns:

            print(
                f"  - {column}"
            )

    if not feature_columns:

        print(
            "\n❌ No usable numeric features found."
        )

        return {
            "status": "NO_FEATURES",
            "dataset": dataset_name,
            "raw": df,
            "supervised": supervised,
        }

    X = (
        supervised[feature_columns]
        .replace(
            [np.inf, -np.inf],
            np.nan,
        )
        .copy()
    )

    # --------------------------------------------------------
    # Feature completeness
    # --------------------------------------------------------

    missing_percent = (
        X.isna()
        .mean()
        .mul(100)
        .sort_values(
            ascending=False
        )
    )

    print("\nFeature missingness:")

    print(
        missing_percent
        .to_string()
    )

    # --------------------------------------------------------
    # Class distribution
    # --------------------------------------------------------

    print("\nClass distribution:")

    class_counts = (
        y.value_counts()
        .sort_index()
    )

    print(
        f"Fetal/non-artifact (0): "
        f"{class_counts.get(0, 0):,}"
    )

    print(
        f"Artifact (1): "
        f"{class_counts.get(1, 0):,}"
    )

    # --------------------------------------------------------
    # Subject distribution
    # --------------------------------------------------------

    subject_counts = (
        groups
        .value_counts()
        .sort_index()
    )

    print(
        f"\nUnique subjects: "
        f"{groups.nunique()}"
    )

    print(
        "\nEvents per subject:"
    )

    print(
        subject_counts
        .to_string()
    )

    return {
        "status": "READY",
        "dataset": dataset_name,
        "raw": df,
        "supervised": supervised,
        "X": X,
        "y": y,
        "groups": groups,
        "feature_columns": feature_columns,
        "label_column": label_column,
        "subject_column": subject_column,
        "uncertain_count": uncertain_count,
        "unlabeled_count": unlabeled_count,
        "class_counts": class_counts.to_dict(),
        "subject_count": groups.nunique(),
    }


