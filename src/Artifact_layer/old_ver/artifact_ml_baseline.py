def build_models(
    n_positive: int,
) -> Dict[str, object]:
    """
    Construct baseline classifiers.

    Models:
        Logistic Regression
        Random Forest
        SVM
        XGBoost
    """

    models = {}

    # --------------------------------------------------------
    # Logistic Regression
    # --------------------------------------------------------

    models["LogisticRegression"] = Pipeline(
        steps=[
            (
                "imputer",
                SimpleImputer(
                    strategy="median"
                ),
            ),

            (
                "scaler",
                StandardScaler(),
            ),

            (
                "classifier",
                LogisticRegression(
                    max_iter=2000,
                    class_weight="balanced",
                    random_state=RANDOM_STATE,
                ),
            ),
        ]
    )

    # --------------------------------------------------------
    # Random Forest
    # --------------------------------------------------------

    models["RandomForest"] = Pipeline(
        steps=[
            (
                "imputer",
                SimpleImputer(
                    strategy="median"
                ),
            ),

            (
                "classifier",
                RandomForestClassifier(
                    n_estimators=300,
                    max_depth=None,
                    min_samples_leaf=2,
                    class_weight="balanced",
                    random_state=RANDOM_STATE,
                    n_jobs=-1,
                ),
            ),
        ]
    )

    # --------------------------------------------------------
    # SVM
    # --------------------------------------------------------

    models["SVM"] = Pipeline(
        steps=[
            (
                "imputer",
                SimpleImputer(
                    strategy="median"
                ),
            ),

            (
                "scaler",
                StandardScaler(),
            ),

            (
                "classifier",
                SVC(
                    probability=True,
                    class_weight="balanced",
                    random_state=RANDOM_STATE,
                ),
            ),
        ]
    )

    # --------------------------------------------------------
    # XGBoost
    # --------------------------------------------------------

    if XGBOOST_AVAILABLE:

        models["XGBoost"] = Pipeline(
            steps=[
                (
                    "imputer",
                    SimpleImputer(
                        strategy="median"
                    ),
                ),

                (
                    "classifier",
                    XGBClassifier(
                        n_estimators=300,
                        max_depth=5,
                        learning_rate=0.05,
                        subsample=0.8,
                        colsample_bytree=0.8,
                        objective="binary:logistic",
                        eval_metric="logloss",
                        random_state=RANDOM_STATE,
                        n_jobs=-1,
                    ),
                ),
            ]
        )

    else:

        print(
            "\n⚠ XGBoost is not installed."
        )

        print(
            "Install it with:"
        )

        print(
            "pip install xgboost"
        )

    return models


# ============================================================
# PROBABILITY EXTRACTION
# ============================================================

def get_prediction_scores(
    model,
    X,
) -> np.ndarray:
    """
    Obtain continuous scores for ROC-AUC / PR-AUC.
    """

    if hasattr(
        model,
        "predict_proba",
    ):

        probabilities = (
            model.predict_proba(X)
        )

        return probabilities[:, 1]

    if hasattr(
        model,
        "decision_function",
    ):

        return (
            model
            .decision_function(X)
        )

    return (
        model
        .predict(X)
        .astype(float)
    )


# ============================================================
# METRICS
# ============================================================

def calculate_metrics(
    y_true,
    y_pred,
    y_score,
) -> Dict[str, float]:
    """
    Calculate binary classification metrics.
    """

    metrics = {
        "accuracy": accuracy_score(
            y_true,
            y_pred,
        ),

        "precision": precision_score(
            y_true,
            y_pred,
            zero_division=0,
        ),

        "recall": recall_score(
            y_true,
            y_pred,
            zero_division=0,
        ),

        "f1": f1_score(
            y_true,
            y_pred,
            zero_division=0,
        ),
    }

    # --------------------------------------------------------
    # ROC-AUC
    # --------------------------------------------------------

    if len(np.unique(y_true)) == 2:

        try:

            metrics["roc_auc"] = (
                roc_auc_score(
                    y_true,
                    y_score,
                )
            )

        except Exception:

            metrics["roc_auc"] = np.nan

        try:

            metrics["pr_auc"] = (
                average_precision_score(
                    y_true,
                    y_score,
                )
            )

        except Exception:

            metrics["pr_auc"] = np.nan

    else:

        metrics["roc_auc"] = np.nan
        metrics["pr_auc"] = np.nan

    return metrics


# ============================================================
# SUBJECT-INDEPENDENT CV
# ============================================================

def run_subject_independent_cv(
    dataset_name: str,
    X: pd.DataFrame,
    y: pd.Series,
    groups: pd.Series,
    feature_columns: List[str],
) -> Tuple[
    pd.DataFrame,
    pd.DataFrame,
    Dict[str, object],
]:
    """
    Run subject-independent GroupKFold validation.

    Returns
    -------
    fold_results
    predictions
    fitted_models
    """

    print_header(
        f"{dataset_name} — SUBJECT-INDEPENDENT VALIDATION"
    )

    n_subjects = groups.nunique()

    print(
        f"Unique subjects: {n_subjects}"
    )

    # --------------------------------------------------------
    # Scientific validity check
    # --------------------------------------------------------

    if n_subjects < MIN_SUBJECTS_FOR_GROUP_CV:

        print(
            "\n⚠ Subject-independent validation "
            "cannot be performed."
        )

        print(
            f"Required subjects: "
            f">= {MIN_SUBJECTS_FOR_GROUP_CV}"
        )

        print(
            f"Available subjects: "
            f"{n_subjects}"
        )

        return (
            pd.DataFrame(),
            pd.DataFrame(),
            {},
        )

    n_splits = min(
        MAX_FOLDS,
        n_subjects,
    )

    cv = GroupKFold(
        n_splits=n_splits
    )

    models = build_models(
        int(y.sum())
    )

    fold_results = []
    prediction_records = []
    fitted_models = {}

    # --------------------------------------------------------
    # Model loop
    # --------------------------------------------------------

    for model_name, model in models.items():

        print_subheader(
            f"{dataset_name} — {model_name}"
        )

        model_fold_results = []

        for fold, (
            train_idx,
            test_idx,
        ) in enumerate(
            cv.split(
                X,
                y,
                groups,
            ),
            start=1,
        ):

            X_train = X.iloc[train_idx]
            X_test = X.iloc[test_idx]

            y_train = y.iloc[train_idx]
            y_test = y.iloc[test_idx]

            train_groups = (
                groups.iloc[train_idx]
            )

            test_groups = (
                groups.iloc[test_idx]
            )

            # ------------------------------------------------
            # Explicit leakage check
            # ------------------------------------------------

            overlap = (
                set(train_groups)
                &
                set(test_groups)
            )

            if overlap:

                raise RuntimeError(
                    "Subject leakage detected! "
                    f"Overlapping subjects: {overlap}"
                )

            # ------------------------------------------------
            # Check both classes in training
            # ------------------------------------------------

            if y_train.nunique() < 2:

                print(
                    f"Fold {fold}: skipped because "
                    f"training data contains only one class."
                )

                continue

            # ------------------------------------------------
            # Clone model
            # ------------------------------------------------

            fold_model = clone(model)

            # ------------------------------------------------
            # Train
            # ------------------------------------------------

            fold_model.fit(
                X_train,
                y_train,
            )

            # ------------------------------------------------
            # Predict
            # ------------------------------------------------

            y_pred = (
                fold_model
                .predict(X_test)
            )

            y_score = (
                get_prediction_scores(
                    fold_model,
                    X_test,
                )
            )

            # ------------------------------------------------
            # Metrics
            # ------------------------------------------------

            metrics = calculate_metrics(
                y_test,
                y_pred,
                y_score,
            )

            metrics.update(
                {
                    "dataset": dataset_name,
                    "model": model_name,
                    "fold": fold,
                    "train_events": len(train_idx),
                    "test_events": len(test_idx),
                    "train_subjects": len(
                        set(train_groups)
                    ),
                    "test_subjects": len(
                        set(test_groups)
                    ),
                    "test_subject_ids": ",".join(
                        sorted(
                            set(
                                test_groups.astype(str)
                            )
                        )
                    ),
                }
            )

            fold_results.append(
                metrics
            )

            model_fold_results.append(
                metrics
            )

            # ------------------------------------------------
            # Store predictions
            # ------------------------------------------------

            for local_index, original_index in enumerate(
                test_idx
            ):

                prediction_records.append(
                    {
                        "dataset": dataset_name,
                        "model": model_name,
                        "fold": fold,
                        "subject_id": str(
                            groups.iloc[
                                original_index
                            ]
                        ),
                        "true_label": int(
                            y.iloc[
                                original_index
                            ]
                        ),
                        "predicted_label": int(
                            y_pred[
                                local_index
                            ]
                        ),
                        "prediction_score": float(
                            y_score[
                                local_index
                            ]
                        ),
                    }
                )

            print(
                f"Fold {fold}: "
                f"F1={metrics['f1']:.4f} | "
                f"Precision={metrics['precision']:.4f} | "
                f"Recall={metrics['recall']:.4f} | "
                f"ROC-AUC={metrics['roc_auc']:.4f}"
                if not np.isnan(metrics["roc_auc"])
                else
                f"Fold {fold}: "
                f"F1={metrics['f1']:.4f} | "
                f"Precision={metrics['precision']:.4f} | "
                f"Recall={metrics['recall']:.4f}"
            )

        # ----------------------------------------------------
        # Train final model on all available supervised data
        # ----------------------------------------------------

        if y.nunique() >= 2:

            final_model = clone(model)

            final_model.fit(
                X,
                y,
            )

            fitted_models[
                model_name
            ] = final_model

    return (
        pd.DataFrame(fold_results),
        pd.DataFrame(prediction_records),
        fitted_models,
    )


# ============================================================
# MODEL SUMMARY
# ============================================================

def summarize_models(
    fold_results: pd.DataFrame,
) -> pd.DataFrame:
    """
    Aggregate fold-level results by model.
    """

    if fold_results.empty:

        return pd.DataFrame()

    metric_columns = [
        "accuracy",
        "precision",
        "recall",
        "f1",
        "roc_auc",
        "pr_auc",
    ]

    summary_rows = []

    for (
        dataset,
        model,
    ), group in fold_results.groupby(
        [
            "dataset",
            "model",
        ]
    ):

        row = {
            "dataset": dataset,
            "model": model,
            "folds": len(group),
        }

        for metric in metric_columns:

            values = group[metric].dropna()

            if len(values) == 0:

                row[
                    f"{metric}_mean"
                ] = np.nan

                row[
                    f"{metric}_std"
                ] = np.nan

            else:

                row[
                    f"{metric}_mean"
                ] = values.mean()

                row[
                    f"{metric}_std"
                ] = values.std(
                    ddof=1
                ) if len(values) > 1 else 0.0

        summary_rows.append(
            row
        )

    summary = pd.DataFrame(
        summary_rows
    )

    if not summary.empty:

        summary = summary.sort_values(
            [
                "dataset",
                "f1_mean",
            ],
            ascending=[
                True,
                False,
            ],
        )

    return summary


# ============================================================
# FEATURE IMPORTANCE
# ============================================================

def extract_feature_importance(
    dataset_name: str,
    model_name: str,
    model,
    feature_columns: List[str],
) -> pd.DataFrame:
    """
    Extract feature importance from models that expose it.

    Supported:
        Random Forest
        XGBoost
    """

    if not hasattr(
        model,
        "named_steps",
    ):

        return pd.DataFrame()

    classifier = model.named_steps.get(
        "classifier"
    )

    if classifier is None:

        return pd.DataFrame()

    importances = None

    # --------------------------------------------------------
    # Tree models
    # --------------------------------------------------------

    if hasattr(
        classifier,
        "feature_importances_",
    ):

        importances = (
            classifier
            .feature_importances_
        )

    if importances is None:

        return pd.DataFrame()

    result = pd.DataFrame(
        {
            "dataset": dataset_name,
            "model": model_name,
            "feature": feature_columns,
            "importance": importances,
        }
    )

    result = result.sort_values(
        "importance",
        ascending=False,
    ).reset_index(
        drop=True
    )

    result["rank"] = (
        np.arange(
            len(result)
        )
        + 1
    )

    return result


