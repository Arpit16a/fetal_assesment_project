def find_existing_column(
    columns,
    candidates: List[str],
) -> Optional[str]:
    """
    Find the first matching column using case-insensitive
    exact matching followed by normalized matching.
    """

    normalized = {
        str(column).strip().lower(): column
        for column in columns
    }

    # Exact matching
    for candidate in candidates:

        key = candidate.strip().lower()

        if key in normalized:
            return normalized[key]

    # Normalized matching
    for column in columns:

        column_normalized = (
            str(column)
            .strip()
            .lower()
            .replace(" ", "_")
            .replace("-", "_")
        )

        for candidate in candidates:

            candidate_normalized = (
                candidate
                .strip()
                .lower()
                .replace(" ", "_")
                .replace("-", "_")
            )

            if column_normalized == candidate_normalized:
                return column

    return None


def detect_label_column(
    df: pd.DataFrame,
) -> Optional[str]:
    """Detect the supervised annotation column."""

    return find_existing_column(
        df.columns,
        LABEL_COLUMN_CANDIDATES,
    )


def detect_subject_column(
    df: pd.DataFrame,
) -> Optional[str]:
    """Detect the subject identifier column."""

    return find_existing_column(
        df.columns,
        SUBJECT_COLUMN_CANDIDATES,
    )


# ============================================================
# LABEL NORMALIZATION
# ============================================================

def normalize_label(value) -> Optional[str]:
    """
    Normalize manual annotation labels.

    Returns
    -------
    artifact
    likely_fetal
    uncertain
    None
    """

    if pd.isna(value):
        return None

    value = str(value).strip().lower()

    if not value:
        return None

    value = value.replace("-", "_")
    value = value.replace(" ", "_")

    if value in {
        "artifact",
        "artefact",
        "artifactual",
        "1",
    }:
        return ARTIFACT_LABEL

    if value in {
        "likely_fetal",
        "fetal",
        "likely_fetal_movement",
        "movement",
        "non_artifact",
        "nonartifact",
        "0",
    }:
        return FETAL_LABEL

    if value in {
        "uncertain",
        "unknown",
        "unsure",
        "?",
    }:
        return UNCERTAIN_LABEL

    return value


