def process_dataset(
    dataset_name: str,
    path: Path,
):
    """
    Load, prepare, and optionally validate one dataset.
    """

    print_header(
        f"{dataset_name} ARTIFACT ML DATASET"
    )

    print(
        f"Input: {path}"
    )

    try:

        raw_df = load_candidate_events(
            dataset_name,
            path,
        )

    except Exception as exc:

        print(
            f"\n❌ Failed to load {dataset_name}: "
            f"{type(exc).__name__}: {exc}"
        )

        return {
            "status": "LOAD_FAILED",
            "dataset": dataset_name,
            "raw": pd.DataFrame(),
        }

    return prepare_dataset(
        dataset_name,
        raw_df,
    )


