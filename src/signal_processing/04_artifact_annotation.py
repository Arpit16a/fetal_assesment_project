"""
04_artifact_annotation.py

STEP 4 — ARTIFACT CANDIDATE ANNOTATION AND VALIDATION
=====================================================

Purpose
-------
This stage converts the candidate events generated by
02_artifact_inspection.py into a human-validated artifact-event
dataset.

This script DOES NOT:

    - train an ML model
    - remove artifacts
    - classify fetal movement
    - modify raw signals
    - manufacture train/test splits

It provides the controlled bridge:

    candidate events
            ↓
    candidate inspection
            ↓
    human annotation
            ↓
    annotation quality control
            ↓
    validated artifact-event dataset

Allowed labels
--------------
    artifact
    likely_fetal
    uncertain

Blank / NaN
-----------
Means:

    not yet reviewed

Important
---------
For FOUR_IMU, the current dataset contains only ONE subject.

Therefore:

    subject-independent validation is NOT possible.

The script explicitly reports this.

A later record-independent exploratory experiment may use:

    record_id

as the grouping variable, but this must NOT be described
as subject-independent validation.
"""

