def validate_candidate_file(
    dataframe: pd.DataFrame,
):

    missing = [
        column
        for column in REQUIRED_COLUMNS
        if column not in dataframe.columns
    ]

    if missing:

        raise ValueError(
            "Candidate file is missing required columns:\n"
            + "\n".join(
                f"  - {column}"
                for column in missing
            )
        )


