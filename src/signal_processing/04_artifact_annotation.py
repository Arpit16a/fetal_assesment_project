def create_annotation_batches(
    dataframe: pd.DataFrame,
):

    print_header(
        "CREATING ANNOTATION BATCHES"
    )

    dataframe = dataframe.copy()

    dataframe[
        "_annotation_index"
    ] = np.arange(
        len(dataframe)
    )

    number_of_batches = math.ceil(
        len(dataframe)
        /
        BATCH_SIZE
    )

    print(
        f"Candidates: {len(dataframe)}"
    )

    print(
        f"Batch size: {BATCH_SIZE}"
    )

    print(
        f"Batches: {number_of_batches}"
    )

    batch_paths = []

    for batch_number in range(
        number_of_batches
    ):

        start = (
            batch_number
            * BATCH_SIZE
        )

        end = min(
            start + BATCH_SIZE,
            len(dataframe),
        )

        batch = dataframe.iloc[
            start:end
        ].copy()

        batch_file = (
            BATCH_ROOT
            /
            f"four_imu_batch_"
            f"{batch_number + 1:03d}.csv"
        )

        batch.to_csv(
            batch_file,
            index=False,
        )

        batch_paths.append(
            batch_file
        )

    print(
        "\n✓ Annotation batches created."
    )

    return batch_paths


