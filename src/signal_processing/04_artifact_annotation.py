def normalize_label(
    value,
):

    if pd.isna(value):

        return None

    value = str(
        value
    ).strip().lower()

    if not value:

        return None

    aliases = {
        "artifact": "artifact",
        "likely_fetal": "likely_fetal",
        "likely fetal": "likely_fetal",
        "fetal": "likely_fetal",
        "uncertain": "uncertain",
        "unknown": "uncertain",
    }

    return aliases.get(
        value,
        None,
    )


def calculate_annotation_status(
    dataframe: pd.DataFrame,
):

    labels = dataframe[
        "manual_label"
    ].apply(
        normalize_label
    )

    total = len(
        dataframe
    )

    reviewed = int(
        labels.notna().sum()
    )

    artifact = int(
        (labels == "artifact").sum()
    )

    likely_fetal = int(
        (labels == "likely_fetal").sum()
    )

    uncertain = int(
        (labels == "uncertain").sum()
    )

    unlabeled = (
        total
        - reviewed
    )

    return {
        "total_candidates": total,
        "reviewed": reviewed,
        "unlabeled": unlabeled,
        "artifact": artifact,
        "likely_fetal": likely_fetal,
        "uncertain": uncertain,
        "completion_percent": (
            100.0 * reviewed / total
            if total
            else 0.0
        ),
    }


