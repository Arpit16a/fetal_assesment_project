def merge_previous_annotations(
    dataframe: pd.DataFrame,
) -> pd.DataFrame:

    dataframe = create_annotation_columns(
        dataframe
    )

    if not ANNOTATION_FILE.exists():

        return dataframe

    previous = pd.read_csv(
        ANNOTATION_FILE
    )

    if (
        "candidate_id"
        not in previous.columns
    ):

        print(
            "WARNING: Existing annotation file "
            "has no candidate_id."
        )

        return dataframe

    previous = previous[
        [
            column
            for column in ANNOTATION_COLUMNS
            if column in previous.columns
        ]
    ].copy()

    merged = dataframe.drop(
        columns=[
            column
            for column in ANNOTATION_COLUMNS
            if column in dataframe.columns
        ],
        errors="ignore",
    ).merge(
        previous,
        on="candidate_id",
        how="left",
    )

    for column in ANNOTATION_COLUMNS:

        if column not in merged.columns:

            merged[column] = ""

    return merged


