def build_candidate_id(
    row: pd.Series,
    index: int,
) -> str:

    dataset = str(
        row.get(
            "dataset",
            DATASET_NAME,
        )
    )

    record = str(
        row.get(
            "record_identifier",
            "",
        )
    )

    segment = str(
        row.get(
            "segment_id",
            "",
        )
    )

    sensor = str(
        row.get(
            "sensor_id",
            "",
        )
    )

    return (
        f"{dataset}"
        f"__record_{record}"
        f"__segment_{segment}"
        f"__sensor_{sensor}"
        f"__candidate_{index + 1:05d}"
    )


