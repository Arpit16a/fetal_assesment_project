def determine_grouping_strategy(
    dataframe: pd.DataFrame,
):

    print_header(
        "FOUR_IMU INDEPENDENT GROUPING ANALYSIS"
    )

    report = {
        "dataset": DATASET_NAME,
        "dataset_name": "Fetal Movement Dataset Recorded Using Four IMUs",
        "subject_independent_validation_possible": False,
        "recommended_current_strategy": None,
        "warnings": [],
    }

    # --------------------------------------------------------------
    # SUBJECT
    # --------------------------------------------------------------

    if "subject_id" in dataframe.columns:

        subjects = (
            dataframe[
                "subject_id"
            ]
            .dropna()
            .astype(str)
            .unique()
            .tolist()
        )

    else:

        subjects = []

    report[
        "unique_subjects"
    ] = subjects

    report[
        "number_of_subjects"
    ] = len(subjects)

    print(
        f"Unique subjects represented in candidates: "
        f"{len(subjects)}"
    )

    if len(subjects) <= 1:

        print(
            "\n⚠ SUBJECT-INDEPENDENT VALIDATION IS NOT POSSIBLE."
        )

        report[
            "warnings"
        ].append(
            "Only one subject is available."
        )

        report[
            "recommended_current_strategy"
        ] = (
            "Do not report subject-independent ML validation. "
            "After annotation, use record-independent "
            "exploratory validation only if sufficient "
            "independent records exist."
        )

    else:

        report[
            "subject_independent_validation_possible"
        ] = True

        report[
            "recommended_current_strategy"
        ] = (
            "Group all folds by subject_id."
        )

    # --------------------------------------------------------------
    # RECORD
    # --------------------------------------------------------------

    record_column = None

    if "record_id" in dataframe.columns:

        record_column = "record_id"

    elif (
        "record_identifier"
        in dataframe.columns
    ):

        record_column = "record_identifier"

    report[
        "record_group_column"
    ] = record_column

    if record_column:

        records = (
            dataframe[
                record_column
            ]
            .dropna()
            .astype(str)
            .unique()
            .tolist()
        )

        report[
            "number_of_records"
        ] = len(records)

        report[
            "records"
        ] = records

        print(
            f"Unique records: {len(records)}"
        )

        if len(records) >= 2:

            print(
                "\n✓ Record-level grouping is available."
            )

            print(
                "  This can support RECORD-INDEPENDENT "
                "exploratory validation."
            )

            print(
                "  It must NOT be called subject-independent."
            )

            report[
                "record_independent_validation_possible"
            ] = True

        else:

            report[
                "record_independent_validation_possible"
            ] = False

            report[
                "warnings"
            ].append(
                "Fewer than two independent records available."
            )

    with open(
        GROUPING_REPORT_FILE,
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            report,
            file,
            indent=4,
        )

    print(
        f"\nGrouping report saved:\n"
        f"{GROUPING_REPORT_FILE}"
    )

    return report


