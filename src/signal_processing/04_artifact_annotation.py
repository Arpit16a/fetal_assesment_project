# PLOT HELPERS
# ======================================================================

def downsample(
    x,
    y,
    maximum=MAX_PLOT_POINTS,
):

    x = np.asarray(
        x
    )

    y = np.asarray(
        y
    )

    if len(x) <= maximum:

        return x, y

    indices = np.linspace(
        0,
        len(x) - 1,
        maximum,
    ).astype(int)

    return (
        x[indices],
        y[indices],
    )


def numeric_array(
    series,
):

    return pd.to_numeric(
        series,
        errors="coerce",
    ).to_numpy(
        dtype=float
    )


def magnitude(
    dataframe,
    prefix,
):

    required = [
        f"{prefix}x",
        f"{prefix}y",
        f"{prefix}z",
    ]

    if not all(
        column in dataframe.columns
        for column in required
    ):

        return None

    x = numeric_array(
        dataframe[
            required[0]
        ]
    )

    y = numeric_array(
        dataframe[
            required[1]
        ]
    )

    z = numeric_array(
        dataframe[
            required[2]
        ]
    )

    return np.sqrt(
        x ** 2
        + y ** 2
        + z ** 2
    )


# ======================================================================
# CANDIDATE SIGNAL EXTRACTION
# ======================================================================

def extract_candidate_signal(
    raw_data: pd.DataFrame,
    candidate: pd.Series,
):

    record_id = str(
        candidate[
            "record_identifier"
        ]
    )

    sensor_id = str(
        candidate.get(
            "sensor_id",
            "",
        )
    )

    segment_id = candidate[
        "segment_id"
    ]

    subset = raw_data.copy()

    # --------------------------------------------------------------
    # Match record
    # --------------------------------------------------------------

    if "record_id" in subset.columns:

        subset = subset[
            subset[
                "record_id"
            ].astype(str)
            == record_id
        ]

    else:

        subset = subset[
            subset[
                "record_identifier"
            ].astype(str)
            == record_id
        ]

    # --------------------------------------------------------------
    # Match sensor
    # --------------------------------------------------------------

    if (
        sensor_id
        and
        "sensor_id"
        in subset.columns
    ):

        subset = subset[
            subset[
                "sensor_id"
            ].astype(str)
            == sensor_id
        ]

    # --------------------------------------------------------------
    # Segment identification
    #
    # The current candidate file does not explicitly
    # save segment start/end timestamps.
    #
    # Therefore we reconstruct the segment context
    # from the record stream.
    # --------------------------------------------------------------

    if subset.empty:

        return subset

    subset = subset.sort_values(
        "timestamp"
    )

    return subset


# ======================================================================
# PLOT ONE CANDIDATE
# ======================================================================

def plot_candidate(
    raw_data: pd.DataFrame,
    candidate: pd.Series,
    output_path: Path,
):

    signal = extract_candidate_signal(
        raw_data,
        candidate,
    )

    if signal.empty:

        return False

    timestamps = pd.to_numeric(
        signal["timestamp"],
        errors="coerce",
    ).to_numpy(
        dtype=float
    )

    valid = np.isfinite(
        timestamps
    )

    signal = signal.loc[
        valid
    ].copy()

    timestamps = timestamps[
        valid
    ]

    if len(signal) < 2:

        return False

    relative_time = (
        timestamps
        - timestamps[0]
    )

    fig, axes = plt.subplots(
        2,
        1,
        figsize=(14, 8),
        sharex=True,
    )

    # --------------------------------------------------------------
    # ACCELERATION
    # --------------------------------------------------------------

    for column in [
        "ax",
        "ay",
        "az",
    ]:

        if column not in signal.columns:

            continue

        values = numeric_array(
            signal[column]
        )

        x, y = downsample(
            relative_time,
            values,
        )

        axes[0].plot(
            x,
            y,
            label=column,
            linewidth=0.8,
        )

    acc_mag = magnitude(
        signal,
        "a",
    )

    if acc_mag is not None:

        x, y = downsample(
            relative_time,
            acc_mag,
        )

        axes[0].plot(
            x,
            y,
            label="acc_magnitude",
            linewidth=1.5,
        )

    axes[0].set_ylabel(
        "Acceleration"
    )

    axes[0].set_title(
        "Accelerometer"
    )

    axes[0].legend()

    axes[0].grid(
        alpha=0.25
    )

    # --------------------------------------------------------------
    # GYROSCOPE
    # --------------------------------------------------------------

    for column in [
        "gx",
        "gy",
        "gz",
    ]:

        if column not in signal.columns:

            continue

        values = numeric_array(
            signal[column]
        )

        x, y = downsample(
            relative_time,
            values,
        )

        axes[1].plot(
            x,
            y,
            label=column,
            linewidth=0.8,
        )

    gyro_mag = magnitude(
        signal,
        "g",
    )

    if gyro_mag is not None:

        x, y = downsample(
            relative_time,
            gyro_mag,
        )

        axes[1].plot(
            x,
            y,
            label="gyro_magnitude",
            linewidth=1.5,
        )

    axes[1].set_ylabel(
        "Gyroscope"
    )

    axes[1].set_xlabel(
        "Time within record (s)"
    )

    axes[1].set_title(
        "Gyroscope"
    )

    axes[1].legend()

    axes[1].grid(
        alpha=0.25
    )

    candidate_id = candidate[
        "candidate_id"
    ]

    reason = candidate.get(
        "candidate_reason",
        "",
    )

    fig.suptitle(
        (
            f"FOUR_IMU Candidate\n"
            f"{candidate_id}\n"
            f"Reason: {reason}"
        ),
        fontsize=12,
    )

    fig.tight_layout()

    fig.savefig(
        output_path,
        dpi=140,
        bbox_inches="tight",
    )

    plt.close(
        fig
    )

    return True


# ======================================================================
# PLOT GENERATION
# ======================================================================

def generate_candidate_plots(
    dataframe: pd.DataFrame,
):

    print_header(
        "GENERATING FOUR_IMU CANDIDATE INSPECTION PLOTS"
    )

    raw_data = load_four_imu_raw()

    print(
        f"Raw shape: {raw_data.shape}"
    )

    generated = 0

    failed = 0

    for index, candidate in dataframe.iterrows():

        candidate_id = candidate[
            "candidate_id"
        ]

        filename = (
            f"{index + 1:05d}_"
            f"{candidate_id.replace('/', '_')}.png"
        )

        output_path = (
            PLOTS_ROOT
            / filename
        )

        if output_path.exists():

            generated += 1
            continue

        try:

            success = plot_candidate(
                raw_data,
                candidate,
                output_path,
            )

            if success:

                generated += 1

            else:

                failed += 1

        except Exception as exc:

            failed += 1

            print(
                f"Failed candidate "
                f"{candidate_id}: "
                f"{repr(exc)}"
            )

        if (
            (index + 1) % 100
            == 0
        ):

            print(
                f"  Processed "
                f"{index + 1}/{len(dataframe)}"
            )

    print()
    print(
        f"Plots available: {generated}"
    )

    print(
        f"Plot failures: {failed}"
    )


